def _resolve_fonts() -> tuple[str, str]:
    """Resolve fontes UI e mono compatíveis com a plataforma atual.

    - Windows: Segoe UI / Consolas (nativas)
    - macOS: SF Pro / SF Mono -> fallback para system fonts
    - Linux: DejaVu Sans / DejaVu Sans Mono (amplamente disponíveis)
    """
    if sys.platform == "win32":
        return ("Segoe UI", "Consolas")
    if sys.platform == "darwin":
        return ("Helvetica Neue", "Menlo")
    return ("DejaVu Sans", "DejaVu Sans Mono")


